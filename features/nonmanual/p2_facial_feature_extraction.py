"""# Build Facial Feature Sequence"""

feature_columns = [
    col for col in facial_df.columns
    if col.startswith("blendshape_")
]

X_face = facial_df[feature_columns].to_numpy()

print("Facial sequence shape:", X_face.shape)

X_face_df = pd.DataFrame(X_face, columns=feature_columns)

# Interpolate short gaps only
X_face_df = X_face_df.interpolate(
    method="linear",
    limit=5,
    limit_area="inside"
)

# Fill remaining missing values with zero
# The face mask will tell the model these frames were unavailable
X_face_df = X_face_df.fillna(0)

X_face = X_face_df.to_numpy(dtype=np.float32)

print("Missing values:", np.isnan(X_face).sum())
print("Sequence shape:", X_face.shape)

face_mask = facial_df["face_detected"].to_numpy(dtype=np.float32)

print("Face mask shape:", face_mask.shape)
print("Detected frames:", int(face_mask.sum()))

X_face = np.clip(X_face, 0, 1)

print("Minimum:", X_face.min())
print("Maximum:", X_face.max())

np.save("X_face.npy", X_face)
np.save("face_mask.npy", face_mask)

