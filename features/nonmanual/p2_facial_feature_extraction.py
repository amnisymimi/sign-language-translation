urllib.request.urlretrieve(model_url, model_path)

print("Face Landmarker model downloaded!")

BaseOptions = mp.tasks.BaseOptions
FaceLandmarker = mp.tasks.vision.FaceLandmarker
FaceLandmarkerOptions = mp.tasks.vision.FaceLandmarkerOptions
RunningMode = mp.tasks.vision.RunningMode

options = FaceLandmarkerOptions(
    base_options=BaseOptions(model_asset_path=model_path),
    running_mode=RunningMode.VIDEO,
    output_face_blendshapes=True,
    output_facial_transformation_matrixes=True,
    num_faces=1
)

print("MediaPipe configured successfully!")

results_data = []

cap = cv2.VideoCapture(video_path)
fps = cap.get(cv2.CAP_PROP_FPS)

with FaceLandmarker.create_from_options(options) as landmarker:

    frame_index = 0

    while True:
        success, frame = cap.read()

        if not success:
            break

        timestamp_ms = int(frame_index * 1000 / fps)

        # Convert BGR to RGB
        rgb_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)

        # Convert to MediaPipe image
        mp_image = mp.Image(
            image_format=mp.ImageFormat.SRGB,
            data=rgb_frame
        )

        # Detect facial features
        result = landmarker.detect_for_video(
            mp_image,
            timestamp_ms
        )

        row = {
            "frame": frame_index,
            "timestamp_ms": timestamp_ms,
            "face_detected": len(result.face_landmarks) > 0
        }

        if result.face_landmarks:
            landmarks = result.face_landmarks[0]

            # Save all facial landmark coordinates
            for i, point in enumerate(landmarks):
                row[f"landmark_{i}_x"] = point.x
                row[f"landmark_{i}_y"] = point.y
                row[f"landmark_{i}_z"] = point.z

            # Save blendshape scores
            if result.face_blendshapes:
                for category in result.face_blendshapes[0]:
                    row[f"blendshape_{category.category_name}"] = (
                        category.score
                    )

        results_data.append(row)
        frame_index += 1

cap.release()

df = pd.DataFrame(results_data)

